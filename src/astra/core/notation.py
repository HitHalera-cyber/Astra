"""Отечественная система обозначений.

Слой отображения между внутренними величинами ядра NASA CEA и тем, что видит
пользователь. Внутренние имена ядра не меняются: здесь только сопоставление
«ключ Astra → обозначение, название, смысл, единица, допустимые значения».

Внутри `astra.core` все величины хранятся в СИ (Па, К, Дж/кг, м/с, м²).
Единица отображения и множитель перевода заданы для каждой величины, чтобы
интерфейс, таблицы и отчёты пересчитывали значения одинаково.
"""

from __future__ import annotations

from dataclasses import dataclass
import math


@dataclass(frozen=True)
class Quantity:
    key: str            # ключ Astra (латиница, используется в коде и проектах)
    symbol: str         # отечественное обозначение
    name: str           # русское название
    meaning: str        # физический смысл
    unit: str           # единица отображения
    si_unit: str        # единица хранения (СИ)
    to_unit: float      # значение_в_единице_отображения = значение_СИ * to_unit
    lower: float = -math.inf   # допустимые значения (в СИ)
    upper: float = math.inf
    description: str = ""
    core_name: str | None = None  # имя величины в ядре NASA CEA, если есть

    def to_display(self, value_si: float) -> float:
        return value_si * self.to_unit

    def from_display(self, value: float) -> float:
        return value / self.to_unit

    def label(self) -> str:
        """Подпись для оси графика или заголовка столбца: «Iуд, м/с»."""
        return f"{self.symbol}, {self.unit}" if self.unit else self.symbol

    def check(self, value_si: float) -> None:
        from .errors import InputError
        if not (self.lower <= value_si <= self.upper) or math.isnan(value_si):
            lo = "−∞" if math.isinf(self.lower) else f"{self.to_display(self.lower):g}"
            hi = "+∞" if math.isinf(self.upper) else f"{self.to_display(self.upper):g}"
            raise InputError(
                f"{self.name} ({self.symbol}) = {self.to_display(value_si):g} {self.unit} "
                f"вне допустимого диапазона [{lo}; {hi}] {self.unit}."
            )


